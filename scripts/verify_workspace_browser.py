"""Real-browser verification of reports, every workspace route, and Run/Live modes.

Requires playwright in the test environment and a running local Streamlit server.
No production records are written. Inputs are actual historical dataset rows.
"""
from __future__ import annotations
import argparse
import json
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))


def main():
    from playwright.sync_api import sync_playwright
    import pandas as pd
    from cyberlab.workspace import PAGE_NAMES
    parser=argparse.ArgumentParser()
    parser.add_argument('--url',default='http://127.0.0.1:8502/')
    parser.add_argument('--chrome',default='C:/Program Files/Google/Chrome/Application/chrome.exe')
    parser.add_argument('--output',type=Path,default=ROOT/'artifacts/workspace-verification')
    args=parser.parse_args()
    args.output.mkdir(parents=True,exist_ok=True)
    result={'url':args.url,'routes':[],'page_errors':[],'limitations':['Historical CICIDS rows are not evidence of attacks occurring now.','No live packet-capture ingestion was generated by this verification.']}
    with sync_playwright() as p:
        browser=p.chromium.launch(executable_path=args.chrome,headless=True)
        page=browser.new_page(viewport={'width':1500,'height':1050},accept_downloads=True)
        page.on('pageerror',lambda error:result['page_errors'].append(str(error)))
        def wait(title):
            page.get_by_role('heading',name=title,exact=True,level=1).wait_for(timeout=90000)
            page.get_by_role('button',name='Stop',exact=True).wait_for(state='hidden',timeout=90000)
            page.wait_for_timeout(300)
            assert page.locator('[data-testid="stException"]').count()==0,page.locator('[data-testid="stException"]').all_text_contents()
        page.goto(args.url,wait_until='domcontentloaded')
        for section in ('Executive summary','Model comparison','Model diagnostics','Learning curve','Dataset & governance','Report generator'):
            page.get_by_test_id('stSidebar').get_by_text(section,exact=True).click()
            wait(section)
            result['routes'].append({'surface':'benchmark','name':section})
        page.get_by_text('Full analytics workspace',exact=True).click()
        wait('Start Here')
        for name in PAGE_NAMES:
            page.get_by_test_id('stSidebar').get_by_text(name,exact=True).click()
            wait(name)
            result['routes'].append({'surface':'workspace','name':name,'charts':page.locator('[data-testid="stPlotlyChart"]').count()})
            if name in ('Overview','ML Lab','Production Readiness'):
                page.screenshot(path=str(args.output/(name.lower().replace(' ','-')+'.png')),full_page=True)
        # Exercise generated artifact, not just the page heading.
        page.get_by_test_id('stSidebar').get_by_text('Code Lab',exact=True).click()
        wait('Code Lab')
        page.get_by_role('button',name='Generate code preview',exact=True).click()
        with page.expect_download() as info:
            page.get_by_role('button',name='Download code preview',exact=True).click()
        info.value.save_as(args.output/'downloaded_preview.py')
        assert 'pd.read_csv' in (args.output/'downloaded_preview.py').read_text(encoding='utf-8')
        result['code_download_verified']=True
        # Actual identifier-reduced feature CSV, not synthetic events or invented scores.
        page.get_by_role('radio',name='Run data',exact=True).click()
        wait('Run data — threat scoring')
        uploader=page.get_by_test_id('stFileUploader').filter(has_text='Run data CSV')
        uploader.locator('input[type=file]').set_input_files(str(ROOT/'report_data/workspace_features.csv'))
        page.get_by_role('button',name='Run detection now',exact=True).click()
        page.get_by_role('heading',name='Window-level scores',exact=True).wait_for(timeout=60000)
        with page.expect_download() as info:
            page.get_by_role('button',name='Download detection results CSV',exact=True).click()
        info.value.save_as(args.output/'uploaded_feature_predictions.csv')
        predictions=pd.read_csv(args.output/'uploaded_feature_predictions.csv')
        source=pd.read_csv(ROOT/'report_data/workspace_features.csv')
        assert len(predictions)==len(source)
        assert predictions.source_ip.isna().all()
        result['uploaded_rows_scored']=len(predictions)
        result['uploaded_suspicious_windows']=int(predictions.suspicious.sum())
        result['no_source_ip_fabrication_verified']=True
        page.screenshot(path=str(args.output/'run-data.png'),full_page=True)
        page.get_by_role('radio',name='Live data',exact=True).click()
        wait('Live data — threat monitoring')
        page.get_by_role('button',name='Fetch snapshot now',exact=True).click()
        page.get_by_text('No recent feature windows.',exact=False).wait_for(timeout=30000)
        result['recent_no_events_state_verified']=True
        page.get_by_text('Include historical / replayed events',exact=True).click()
        page.get_by_role('button',name='Fetch snapshot now',exact=True).click()
        page.get_by_role('heading',name='Window-level scores',exact=True).wait_for(timeout=30000)
        assert page.get_by_text('HISTORICAL REPLAY VIEW:',exact=False).count()==1
        result['historical_elasticsearch_snapshot_verified']=True
        page.screenshot(path=str(args.output/'live-historical-replay.png'),full_page=True)
        assert not result['page_errors'],result['page_errors']
        assert sum(row['surface']=='workspace' for row in result['routes'])==len(PAGE_NAMES)
        browser.close()
    (args.output/'verification.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
    print(json.dumps(result,indent=2))


if __name__=='__main__':
    main()
